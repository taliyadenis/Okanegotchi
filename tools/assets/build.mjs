import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { PNG } from 'pngjs'

export const root = fileURLToPath(new URL('../../', import.meta.url))
export function decodeSource(raw) {
  if(!raw.subarray(0,8).equals(Buffer.from([137,80,78,71,13,10,26,10]))) throw Error('Not a PNG')
  let end=8, found=false
  while(end+12<=raw.length) {
    const length=raw.readUInt32BE(end), type=raw.toString('ascii',end+4,end+8)
    end+=length+12
    if(end>raw.length) throw Error('Truncated PNG')
    if(type==='IEND'){found=true;break}
  }
  if(!found) throw Error('Missing IEND')
  return { png:PNG.sync.read(raw.subarray(0,end)), trailing:raw.length-end }
}
export const rgb = hex => hex ? hex.slice(1).match(/../g).map(v=>parseInt(v,16)) : [0,0,0]
export const rgb565 = hex => {const [r,g,b]=rgb(hex);return ((r>>3)<<11)|((g>>2)<<5)|(b>>3)}

export function build() {
  const manifest=JSON.parse(fs.readFileSync(path.join(root,'assets/manifest.json'),'utf8'))
  const web=path.join(root,'public/assets/v1'), firmware=path.join(root,'firmware/generated')
  const {width,height}=manifest.canvas
  if(width!==32||height!==32||manifest.asset_version!==1) throw Error('Unsupported asset contract')
  const output=new Map(), header=['// Generated by npm run assets:build. Do not edit.','#pragma once','#include <stdint.h>','namespace okanegotchi {','constexpr uint8_t ASSET_VERSION = 1;','constexpr uint8_t FRAME_WIDTH = 32, FRAME_HEIGHT = 32;','// Frame-major, row-major pixels. RGB565 numeric words; no byte swap. Mask MSB first, 1 = opaque.']
  const array=(type,name,values)=>{
    header.push('static const '+type+' '+name+'['+values.length+'] = {')
    for(let i=0;i<values.length;i+=32) header.push('  '+Array.from(values.slice(i,i+32)).join(',')+',')
    header.push('};')
  }
  for(const [name,xy] of Object.entries(manifest.anchors)) array('uint8_t','anchor_'+name,xy)
  const report={frames:0,indexed_bytes:0,mask_bytes:0,palette_bytes:0,rgb565_reference_bytes:0,sheets:{}}
  for(const [pet,preset] of Object.entries(manifest.presets)) {
    const palette=preset.palette, colors=new Map(palette.map((c,i)=>[c,i]))
    if(palette[0]!==null || palette.length>16 || colors.size!==palette.length) throw Error('Invalid indexed palette')
    array('uint16_t',pet+'_palette',palette.map(rgb565));report.palette_bytes+=palette.length*2
    for(const [state,animation] of Object.entries(manifest.animations)) {
      const name=pet+'_'+state, {png,trailing}=decodeSource(fs.readFileSync(path.join(root,'assets/source',pet,animation.file)))
      if(png.width!==width*animation.frames||png.height!==height) throw Error(name+': invalid dimensions')
      if(!Number.isInteger(animation.frame_ms)||animation.frame_ms<1) throw Error('Invalid timing')
      const indices=[], mask=new Uint8Array(animation.frames*width*height/8)
      for(let f=0;f<animation.frames;f++) for(let y=0;y<height;y++) for(let x=0;x<width;x++) {
        const p=(y*png.width+f*width+x)*4, alpha=png.data[p+3]
        if(alpha!==0&&alpha!==255) throw Error(name+': partial transparency')
        const color='#'+png.data.subarray(p,p+3).toString('hex'), index=alpha?colors.get(color):0
        if(index===undefined) throw Error(name+': unmapped color '+color)
        const i=indices.length; indices.push(index); if(index) mask[i>>3]|=1<<(7-(i&7))
      }
      array('uint8_t',name+'_indices',indices);array('uint8_t',name+'_mask',mask)
      header.push('constexpr uint8_t '+name+'_frames = '+animation.frames+';','constexpr uint16_t '+name+'_frame_ms = '+animation.frame_ms+';','constexpr uint16_t '+name+'_duration_ms = '+(animation.duration_ms??0)+';')
      header.push('#ifdef OKANEGOTCHI_INCLUDE_RGB565_REFERENCE')
      array('uint16_t',name+'_rgb565',indices.map(i=>rgb565(palette[i])))
      header.push('#endif')
      output.set(name+'.bin',Buffer.from(indices)); output.set(name+'.png',PNG.sync.write(png))
      report.frames+=animation.frames;report.indexed_bytes+=indices.length;report.mask_bytes+=mask.length;report.rgb565_reference_bytes+=indices.length*2
      report.sheets[name]={frames:animation.frames,width:png.width,height:png.height,trailing_bytes_ignored:trailing}
    }
  }
  header.push('inline uint16_t pixel565(const uint8_t* indices, const uint16_t* palette, uint32_t offset) { return palette[indices[offset]]; }','} // namespace okanegotchi')
  // Validate all sources before replacing output. Original exports remain untouched.
  fs.mkdirSync(web,{recursive:true});fs.mkdirSync(firmware,{recursive:true})
  for(const [name,data] of output) fs.writeFileSync(path.join(web,name),data)
  fs.writeFileSync(path.join(web,'manifest.json'),JSON.stringify(manifest,null,2)+'\n')
  fs.writeFileSync(path.join(firmware,'okanegotchi_assets.h'),header.join('\n')+'\n')
  fs.writeFileSync(path.join(firmware,'asset-report.json'),JSON.stringify(report,null,2)+'\n')
  console.log('Generated '+Object.keys(report.sheets).length+' sheets / '+report.frames+' frames. Indexed: '+report.indexed_bytes+' B; masks: '+report.mask_bytes+' B; palettes: '+report.palette_bytes+' B.')
  return report
}
if(process.argv[1] && path.resolve(process.argv[1])===fileURLToPath(import.meta.url)) build()
